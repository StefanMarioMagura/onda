"""Generate app/lib/data/parties_ches2024.dart from the CHES 2024 dataset.

Keeps the Spanish parties and the three axes ONDA uses, so party positions in
the app are traceable to the source and never typed by hand.

    curl -L -o /tmp/ches.csv https://github.com/chesdata/chesdata.github.io/releases/download/ches-europe/CHES_2024_final_v2.csv
    python tools/ches_to_dart.py /tmp/ches.csv

Writes the Dart file and docs/producto/ches2024_espana.csv (the extract).
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPAIN = "5"
AXES = {"lrecon": "economia", "galtan": "sociedad", "regions": "territorio"}

# Full names, by CHES party_id. Leaders only where the role is unambiguous;
# review when leaderships change.
NAMES = {
    "501": ("PSOE", "Partido Socialista Obrero Español", "Pedro Sánchez"),
    "502": ("PP", "Partido Popular", "Alberto Núñez Feijóo"),
    "527": ("Vox", "Vox", "Santiago Abascal"),
    "551": ("Sumar", "Sumar", None),
    "525": ("Podemos", "Podemos", "Ione Belarra"),
    "504": ("IU", "Izquierda Unida", "Antonio Maíllo"),
    "511": ("ERC", "Esquerra Republicana de Catalunya", "Oriol Junqueras"),
    "550": ("Junts", "Junts per Catalunya", "Carles Puigdemont"),
    "524": ("EH Bildu", "Euskal Herria Bildu", "Arnaldo Otegi"),
    "506": ("PNV", "Partido Nacionalista Vasco", "Aitor Esteban"),
    "513": ("BNG", "Bloque Nacionalista Galego", "Ana Pontón"),
    "517": ("CC", "Coalición Canaria", None),
    "553": ("UPN", "Unión del Pueblo Navarro", None),
    "552": ("SALF", "Se Acabó La Fiesta", "Alvise Pérez"),
}


def main(path: str) -> None:
    rows = [r for r in csv.DictReader(open(path, encoding="utf-8")) if r["country"] == SPAIN]
    rows.sort(key=lambda r: -float(r["seat"] or 0))

    extract = ROOT / "docs/producto/ches2024_espana.csv"
    with extract.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["party_id", "party", "seat", *AXES])
        for r in rows:
            w.writerow([r["party_id"], r["party"], r["seat"], *(r[a] for a in AXES)])

    lines = [
        "// GENERATED by workers/tools/ches_to_dart.py from CHES 2024 (chesdata.eu). Do not edit.",
        "// Party positions on 0-10 scales: lrecon (economía), galtan (sociedad), regions (territorio).",
        "import '../domain/affinity.dart';",
        "",
        "const partiesChes2024 = <Party>[",
    ]
    for r in rows:
        short, name, leader = NAMES[r["party_id"]]
        pos = ", ".join(f"PolAxis.{AXES[a]}: {float(r[a]):.2f}" for a in AXES)
        leader_dart = f"'{leader}'" if leader else "null"
        lines.append(
            f"  Party(id: '{r['party_id']}', short: '{short}', name: '{name}', leader: {leader_dart}, "
            f"seats: {int(float(r['seat'] or 0))}, position: {{{pos}}}),"
        )
    lines += ["];", ""]
    (ROOT / "app/lib/data/parties_ches2024.dart").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} parties written")


if __name__ == "__main__":
    main(sys.argv[1])
